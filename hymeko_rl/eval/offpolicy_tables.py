"""Render the off-policy campaign journal into result tables (Markdown + LaTeX).

Reads the per-cell ``.jsonl`` written by ``offpolicy_eval.compare_offpolicy(..., journal=)`` and emits, per
``(task, algo)``, the **curve-max** of HSiKAN vs the params-matched MLP (median, IQR, worst) plus a verdict:
HSiKAN/MLP wins only when the median gap **exceeds the cross-seed IQR**; otherwise it is a tie (the standing
rule — never credit structure inside the noise). The LaTeX table is `booktabs`, drop-in for the extended
abstract.

    python -m hymeko_rl.eval.offpolicy_tables --journal reports/<run>.jsonl \
        --md reports/<run>-tables.md --tex reports/<run>-tables.tex
"""
from __future__ import annotations

import argparse
import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from hymeko_rl.eval.evaluate import now_stamp
from hymeko_rl.eval.offpolicy_eval import aggregate_records

_TASK_LABEL = {"cartpole": "Inverted pendulum (2-vtx)", "galambos": "Galambos grasp (6-vtx)",
               "arm6dof": "6-DOF arm reach (6-vtx)", "quadruped": "Quadruped (14-vtx)"}


def _read_records(journal: Path) -> list[dict[str, Any]]:
    return [json.loads(line) for line in journal.read_text(encoding="utf-8").splitlines() if line.strip()]


def _verdict(h_med: float, h_iqr: float, m_med: float, m_iqr: float) -> str:
    """HSiKAN-vs-MLP verdict on curve-max: a win needs the median gap to exceed the larger cross-seed IQR."""
    gap = h_med - m_med
    tol = max(h_iqr, m_iqr, 1e-9)
    if gap > tol:
        return f"HSiKAN +{gap:.2f}"
    if gap < -tol:
        return f"MLP +{-gap:.2f}"
    return f"tie ({gap:+.2f})"


def _rows(records: Sequence[dict[str, Any]]) -> list[dict[str, Any]]:
    """One row per (task, algo): the paired HSiKAN/MLP curve-max stats + verdict, ordered by task then algo."""
    agg = aggregate_records(records)
    pairs: dict[tuple[str, str], dict[str, dict[str, Any]]] = {}
    for (task, algo, backbone), stats in agg.items():
        pairs.setdefault((task, algo), {})[backbone] = stats
    rows: list[dict[str, Any]] = []
    task_order = list(_TASK_LABEL)
    for (task, algo) in sorted(pairs, key=lambda k: (task_order.index(k[0]) if k[0] in task_order else 99, k[1])):
        h, m = pairs[(task, algo)].get("hsikan"), pairs[(task, algo)].get("mlp")
        if h is None or m is None:
            continue
        rows.append(dict(
            task=task, algo=algo,
            h_params=h["n_params"], m_params=m["n_params"], n_seeds=h["n_seeds"],
            h_med=h["curve_max_median"], h_iqr=h["curve_max_iqr"], h_worst=h["curve_max_worst"],
            m_med=m["curve_max_median"], m_iqr=m["curve_max_iqr"], m_worst=m["curve_max_worst"],
            verdict=_verdict(h["curve_max_median"], h["curve_max_iqr"],
                             m["curve_max_median"], m["curve_max_iqr"])))
    return rows


def to_markdown(records: Sequence[dict[str, Any]]) -> str:
    rows = _rows(records)
    head = ("| Task | Algo | Seeds | HSiKAN params | HSiKAN curve-max (med ± IQR, worst) | "
            "MLP params | MLP curve-max (med ± IQR, worst) | Verdict (vs IQR) |")
    sep = "|" + "---|" * 8
    lines = [f"# Off-policy architecture eval — curve-max  ({now_stamp()})", "", head, sep]
    for r in rows:
        lines.append(
            f"| {_TASK_LABEL.get(r['task'], r['task'])} | {r['algo'].upper()} | {r['n_seeds']} | "
            f"{r['h_params']} | {r['h_med']:.2f} ± {r['h_iqr']:.2f} ({r['h_worst']:.2f}) | "
            f"{r['m_params']} | {r['m_med']:.2f} ± {r['m_iqr']:.2f} ({r['m_worst']:.2f}) | {r['verdict']} |")
    return "\n".join(lines) + "\n"


def to_latex(records: Sequence[dict[str, Any]]) -> str:
    rows = _rows(records)
    out = [r"% generated by hymeko_rl.eval.offpolicy_tables — " + now_stamp(),
           r"\begin{table}[t]", r"\centering", r"\small",
           r"\caption{Off-policy curve-max (mean return over the eval schedule, median$\pm$IQR over seeds) of "
           r"the HSiKAN signed-hypergraph backbone vs.\ a params-matched MLP, fixed algorithm. A verdict is "
           r"credited only when the median gap exceeds the cross-seed IQR.}",
           r"\label{tab:offpolicy-archcmp}",
           r"\begin{tabular}{llcrlrll}", r"\toprule",
           r"Task & Algo & Seeds & \multicolumn{2}{c}{HSiKAN (params / curve-max)} & "
           r"\multicolumn{2}{c}{MLP (params / curve-max)} & Verdict \\", r"\midrule"]
    for r in rows:
        out.append(
            f"{_TASK_LABEL.get(r['task'], r['task'])} & {r['algo'].upper()} & {r['n_seeds']} & "
            f"{r['h_params']} & ${r['h_med']:.2f}\\pm{r['h_iqr']:.2f}$ & "
            f"{r['m_params']} & ${r['m_med']:.2f}\\pm{r['m_iqr']:.2f}$ & {r['verdict']} \\\\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--journal", required=True, help="the per-cell .jsonl from the campaign")
    ap.add_argument("--md", default=None, help="write the Markdown table here")
    ap.add_argument("--tex", default=None, help="write the LaTeX (booktabs) table here")
    a = ap.parse_args(argv)
    records = _read_records(Path(a.journal))
    md, tex = to_markdown(records), to_latex(records)
    if a.md:
        Path(a.md).write_text(md, encoding="utf-8")
    if a.tex:
        Path(a.tex).write_text(tex, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
